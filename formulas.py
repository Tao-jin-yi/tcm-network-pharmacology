DEFAULT_FORMULA = "本项目示例方（六味地黄丸加黄芪·丹参·甘草）"


def formula_names() -> List[str]:
    """全部方剂名（示例方排在首位）。"""
    names = [DEFAULT_FORMULA]
    names += [n for n in FORMULAS if n != DEFAULT_FORMULA]
    return names


def get_formula(name: Optional[str] = None) -> dict:
    """取方剂信息，未知方名回退到默认方。"""
    return FORMULAS.get(name or DEFAULT_FORMULA, FORMULAS[DEFAULT_FORMULA])


def formula_herbs(name: Optional[str] = None) -> List[str]:
    """方剂的组成药材（按剂量字典顺序）。"""
    return list(get_formula(name)["dosage"])


def formula_rows(name: Optional[str] = None) -> List[dict]:
    """组成表：药名、剂量、君臣佐使、性味、归经、分类、功效主治。"""
    try:
        from herb_info import get_herb_info
    except ImportError:  # pragma: no cover
        get_herb_info = None  # type: ignore

    formula = get_formula(name)
    roles: Dict[str, str] = {}
    for role, members, _ in formula["roles"]:
        for herb in members:
            roles.setdefault(herb, role)

    rows = []
    for herb, dose in formula["dosage"].items():
        info = get_herb_info(herb) if get_herb_info else None
        info = info or {}
        rows.append({
            "中药": herb,
            "剂量 (g)": dose,
            "角色": roles.get(herb, "—"),
            "性味": info.get("nature", "—"),
            "归经": info.get("meridian", "—"),
            "分类": info.get("category", "—"),
            "功效主治": info.get("action", "—"),
        })
    return rows


def formula_coverage(name: Optional[str], available_herbs) -> Tuple[int, int, List[str]]:
    """数据覆盖率：方中药材中有成分-靶点数据的数量。

    返回 (有数据的药材数, 药材总数, 有数据的药材列表)。
    """
    herbs = formula_herbs(name)
    available = set(available_herbs or [])
    hit = [h for h in herbs if h in available]
    return len(hit), len(herbs), hit
