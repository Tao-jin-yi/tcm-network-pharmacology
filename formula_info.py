def formula_rows() -> List[dict]:
    """组成表：药名、剂量、君臣佐使、性味归经、功效主治（性味部分来自 herb_info）。"""
    try:
        from herb_info import get_herb_info
    except ImportError:
        get_herb_info = None  # type: ignore

    rows = []
    for role, herbs, _ in ROLE_GROUPS:
        for herb in herbs:
            info = get_herb_info(herb) or {} if get_herb_info else {}
            rows.append({
                "中药": herb,
                "剂量 (g)": DOSAGE.get(herb, "—"),
                "角色": role,
                "性味": info.get("nature", "—"),
                "归经": info.get("meridian", "—"),
                "分类": info.get("category", "—"),
                "功效主治": info.get("action", "—"),
            })
    return rows
