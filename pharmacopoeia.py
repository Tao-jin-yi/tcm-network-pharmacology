# ================================================================ 工具函数
def get_pharm_herb(name: str) -> Optional[dict]:
    """按药名取目录记录，未收录返回 None。"""
    return HERB_CATALOG.get(name)


def list_categories() -> List[str]:
    """按目录中的出现顺序返回功能分类列表。"""
    seen: List[str] = []
    for v in HERB_CATALOG.values():
        if v["category"] not in seen:
            seen.append(v["category"])
    return seen


def search_herbs(keyword: str = "", category: Optional[str] = None,
                 gangmu: Optional[bool] = None,
                 toxic_only: bool = False) -> Dict[str, dict]:
    """检索药材目录。

    keyword     匹配药材名 / 性味 / 归经 / 功效（子串，忽略大小写）
    category    限定功能分类（完整字符串，见 list_categories()）
    gangmu      None=不限；True=仅《本草纲目》亦收载；False=仅后世著作收载
    toxic_only  True=仅显示有毒药材
    """
    kw = (keyword or "").strip().lower()
    result: Dict[str, dict] = {}
    for name, info in HERB_CATALOG.items():
        if category and info["category"] != category:
            continue
        if gangmu is not None and (BEN_CAO in info["works"]) != gangmu:
            continue
        if toxic_only and not info["toxic"]:
            continue
        if kw:
            hay = " ".join([name, info["nature"], info["meridian"],
                            info["action"], info["category"]]).lower()
            if kw not in hay:
                continue
        result[name] = info
    return result


def catalog_stats() -> dict:
    """目录统计：总数、分类数、本草纲目收载数、有毒药材数。"""
    return {
        "total": len(HERB_CATALOG),
        "categories": len(list_categories()),
        "gangmu": sum(1 for v in HERB_CATALOG.values() if BEN_CAO in v["works"]),
        "toxic": sum(1 for v in HERB_CATALOG.values() if v["toxic"]),
    }


if __name__ == "__main__":
    s = catalog_stats()
    print(f"目录共收载 {s['total']} 味药材，{s['categories']} 个功能分类；"
          f"《本草纲目》亦收载 {s['gangmu']} 味，有毒药材 {s['toxic']} 味。")
